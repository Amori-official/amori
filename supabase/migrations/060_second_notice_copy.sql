-- ============================================================
-- 060_second_notice_copy.sql — SECOND 상단 안내 문구(세컨드/구버전 구분)
-- ============================================================
-- 세컨드는 흠이 있지만 구버전(핸드타월)은 흠 없이 리뉴얼 이전 버전일 뿐이므로,
-- 안내 문구에서 둘을 명확히 구분한다. renewal_notice 텍스트만 교체.
-- ============================================================

begin;

update public.products
   set renewal_notice = E'사용엔 문제없어요 — 세컨드·구버전 특가\n· 세컨드: 제작 과정에서 생긴 아주 작은 흠이 있는 제품이에요. 아래 사진에서 어떤 흠이 있을 수 있는지 꼭 확인하신 뒤 구매해주세요.\n· 구버전(핸드타월): 흠이 있는 게 아니라 리뉴얼 이전 버전이에요. 상태는 정상이며 특가로 드립니다.\n\n색상·옵션은 선택하신 대로 발송되며, 세컨드 제품은 흠의 종류·위치를 지정하실 수 없습니다.\n\n*단순변심에 의한 교환·환불은 불가합니다.*',
       updated_at = now()
 where slug = 'second';

commit;
